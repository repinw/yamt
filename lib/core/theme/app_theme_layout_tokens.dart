/// Layout values used by app-wide Material component themes.
abstract final class AppThemeSpacing {
  /// Medium spacing.
  static const double md = 12;

  /// Extra-large spacing.
  static const double xl = 16;
}

/// Corner radii used by app-wide Material component themes.
abstract final class AppThemeRadius {
  /// Medium radius.
  static const double md = 14;

  /// Large radius.
  static const double lg = 16;

  /// Extra-large radius.
  static const double xl = 24;
}
