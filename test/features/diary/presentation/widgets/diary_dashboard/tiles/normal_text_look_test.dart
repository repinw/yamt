/// Grid widths of the narrow phones, plus a 360 dp screen (328 dp grid).
const _gridWidths = [288.0, 311.0, 328.0, 379.0];

final Map<String, String> _written = {};
final String? _writeTo = Platform.environment['LOOK_PINS_OUT'];

/// Checks the look under [root] against the pin of [key], or records it.
void _expectLook(WidgetTester tester, String key, Finder root) {
  // Master overflows by a pixel or two in a few of these scenarios; the look
  // is what is pinned, so an overflow report alone does not fail.
  final error = tester.takeException();
  if (error != null && !error.toString().contains('overflowed')) {
    fail('$key threw $error');
  }
  final rows = renderedLook(tester, root);
  final hash = lookHash(rows);
  if (_writeTo != null) {
    _written[key] = hash;
    return;
  }
  expect(
    hash,
    normalTextLookPins[key],
    reason: '$key at text size 1 differs from master:\n${rows.join('\n')}',
  );
}

void main() {
  setUpAll(loadAppFonts);
  tearDownAll(() {
    final path = _writeTo;
    if (path == null) return;
    final lines = [
      for (final key in _written.keys.toList()..sort())
        "  '$key': '${_written[key]}',",
    ];
    File(path).writeAsStringSync(
      '// Generated by normal_text_look_test.dart; see there.\n\n'
      '/// Hash of the look of every scenario at text size 1, from master '
      '78f985109, except the ten scenarios that overflowed there: macros bars '
      's4x1 and budget card training at 288 dp (see\n'
      '/// normal_text_look_test.dart), which are the branch look.\n'
      'const normalTextLookPins = <String, String>{\n'
      '${lines.join('\n')}\n'
      '};\n',
    );
  });

  for (final locale in ['de', 'en']) {
    final l10n = lookupAppLocalizations(Locale(locale));
    final macros = normalTextMacros(l10n);

    for (final width in _gridWidths) {
      for (final mode in diaryMacrosTileSpec.modes) {
        for (final size in diaryMacrosTileSpec.sizes) {
          final key = 'macros $locale $width $mode ${size.name}';
          testWidgets(key, (tester) async {
            await pumpInTileSlot(
              tester,
              locale: locale,
              slot: size,
              gridWidth: width,
              textScale: 1,
              child: DiaryMacrosTileLayout(
                macros: macros,
                size: size,
                mode: mode,
              ),
            );
            _expectLook(tester, key, find.byKey(largeTextSlotKey));
          });
        }
      }

      for (final bars in [true, false]) {
        for (final size in diaryMealsTileSpec.sizes) {
          final key = 'meals $locale $width bars=$bars ${size.name}';
          testWidgets(key, (tester) async {
            await pumpInTileSlot(
              tester,
              locale: locale,
              slot: size,
              gridWidth: width,
              textScale: 1,
              child: DiaryMealsTileLayout(
                meals: normalTextMeals(),
                numberFormat: normalTextFormat(locale),
                size: size,
                bars: bars,
              ),
            );
            _expectLook(tester, key, find.byKey(largeTextSlotKey));
          });
        }
      }

      for (final type in DiaryDayType.values) {
        for (final mode in diaryDayTypeTileSpec.modes) {
          for (final size in diaryDayTypeTileSpec.sizes) {
            final key =
                'day type $locale $width ${type.name} $mode ${size.name}';
            testWidgets(key, (tester) async {
              final settings = FakeCalorieSettingsRepository(
                initialSettings: CalorieGoalSettings.single(
                  dailyKcalGoal: 2000,
                  calculatorProfile: null,
                  effectiveDate: DateTime(2026, 9),
                  trainingWeekdays: [
                    if (type == DiaryDayType.training) normalTextDay.weekday,
                  ],
                  pauseDayKeys: [
                    if (type == DiaryDayType.pause) localDayKey(normalTextDay),
                  ],
                ),
              );
              addTearDown(settings.dispose);
              await pumpInTileSlot(
                tester,
                locale: locale,
                slot: size,
                gridWidth: width,
                textScale: 1,
                overrides: [
                  clockProvider.overrideWithValue(
                    () => normalTextDay.add(const Duration(hours: 12)),
                  ),
                  calorieSettingsRepositoryProvider.overrideWithValue(settings),
                ],
                child: diaryDayTypeTile.builder(
                  DiaryTileArgs(day: normalTextDay, size: size, mode: mode),
                ),
              );
              _expectLook(tester, key, find.byKey(largeTextSlotKey));
            });
          }
        }
      }
    }

    for (final width in [130.0, 160.0, 300.0]) {
      for (final eaten in [false, true]) {
        for (final details in [false, true]) {
          for (final pause in [false, true]) {
            final key =
                'budget macro column $locale ${width.round()} '
                'eaten=$eaten details=$details pause=$pause';
            testWidgets(key, (tester) async {
              await tester.pumpWidget(
                MaterialApp(
                  locale: Locale(locale),
                  localizationsDelegates: appLocalizationsDelegates,
                  supportedLocales: AppLocalizations.supportedLocales,
                  home: Scaffold(
                    body: SingleChildScrollView(
                      child: Align(
                        alignment: Alignment.topLeft,
                        child: SizedBox(
                          key: largeTextSlotKey,
                          width: width,
                          child: DiaryBudgetMacroColumn(
                            data: normalTextCardData(pause: pause),
                            showDetails: details,
                            showEaten: eaten,
                            numberFormat: normalTextFormat(locale),
                          ),
                        ),
                      ),
                    ),
                  ),
                ),
              );
              _expectLook(tester, key, find.byKey(largeTextSlotKey));
            });
          }
        }
      }
    }

    for (final width in [343.0, 288.0]) {
      for (final type in DiaryDayType.values) {
        for (final details in [false, true]) {
          for (final eaten in [false, true]) {
            final key =
                'budget card $locale ${width.round()} ${type.name} '
                'eaten=$eaten details=$details';
            testWidgets(key, (tester) async {
              FakeAccelerometer();
              final settings = FakeCalorieSettingsRepository(
                initialSettings: CalorieGoalSettings.single(
                  dailyKcalGoal: 2000,
                  calculatorProfile: null,
                  effectiveDate: DateTime(2026),
                  trainingWeekdays: [
                    if (type == DiaryDayType.training) normalTextDay.weekday,
                  ],
                  pauseDayKeys: [
                    if (type == DiaryDayType.pause) localDayKey(normalTextDay),
                  ],
                ),
              );
              addTearDown(settings.dispose);
              await tester.pumpWidget(
                ProviderScope(
                  key: UniqueKey(),
                  overrides: [
                    appPreferencesProvider.overrideWithValue(
                      MemoryAppPreferences(),
                    ),
                    clockProvider.overrideWithValue(
                      () => normalTextDay.add(const Duration(hours: 12)),
                    ),
                    calorieSettingsRepositoryProvider.overrideWithValue(
                      settings,
                    ),
                  ],
                  child: MaterialApp(
                    locale: Locale(locale),
                    localizationsDelegates: appLocalizationsDelegates,
                    supportedLocales: AppLocalizations.supportedLocales,
                    home: Scaffold(
                      body: SingleChildScrollView(
                        child: Align(
                          alignment: Alignment.topLeft,
                          child: SizedBox(
                            key: largeTextSlotKey,
                            width: width,
                            child: DiaryBudgetCard(
                              data: normalTextCardData(
                                pause: type == DiaryDayType.pause,
                              ),
                              showDetails: details,
                              showEaten: eaten,
                              today: normalTextDay,
                            ),
                          ),
                        ),
                      ),
                    ),
                  ),
                ),
              );
              await tester.pump(const Duration(milliseconds: 500));
              _expectLook(tester, key, find.byKey(largeTextSlotKey));
            });
          }
        }
      }
    }
  }
}
