// At the default text size the tiles and the budget card look as they did
// before the large-text rules (release 3.11.0, master 78f985109): every text
// and every leaf box sits where it sat, to a hundredth of a dp.
//
// The pins in normal_text_look_pins.dart come from that master. To renew
// them after a change of the look on purpose, run this file on the commit
// that should become the reference, with LOOK_PINS_OUT=<path to the pins>.
//
// Ten scenarios differ from master on purpose: master overflowed there at
// text size 1 (macro bars 4×1 on the 288 dp grid by 0.9 dp, and the budget
// card on a 288 dp card on a training day by 44 px), and the branch fixes
// the overflow. Their pins are the branch's look.
